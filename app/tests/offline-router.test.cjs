const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');

function evaluate(path, requireFn) {
  const code = ts.transpileModule(fs.readFileSync(path, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  const exports = {};
  vm.runInNewContext(code, { exports, require: requireFn, Map, Set, Math, JSON });
  return exports;
}

const { OfflineRouter } = evaluate('src/offline/router.ts', () => ({}));
const bundle = evaluate('src/offline/bundle.ts', () => ({}));
const { offlineFare } = evaluate('src/offline/offlinePlan.ts', (name) => {
  if (name === './bundle') return bundle;
  if (name === './router') return { OfflineRouter };
  throw new Error(`Unexpected module ${name}`);
});

const graph = JSON.parse(fs.readFileSync('tests/fixtures/routing-graph.json', 'utf8'));
const reference = JSON.parse(fs.readFileSync('tests/fixtures/reference-routes.json', 'utf8'));
const router = new OfflineRouter(graph, []);

test('matches the API reference router on time, changes and distance', () => {
  // Generated by api/services/offline_router.py over the same graph. Equal-cost
  // ties may name a different pattern, so routes are compared by cost.
  for (const r of reference) {
    const got = router.route(r.from, r.to, r.strategy);
    assert.ok(got, `${r.from} -> ${r.to} routes`);
    assert.equal(got.changes, r.changes, `${r.from} -> ${r.to} ${r.strategy} changes`);
    assert.ok(Math.abs(got.minutes - r.minutes) < 0.01, `${r.from} -> ${r.to} minutes`);
    assert.ok(Math.abs(got.km - r.km) < 0.01, `${r.from} -> ${r.to} km`);
  }
});

test('legs connect, and fewer changes never has more changes than shortest distance', () => {
  for (const r of reference.filter((x) => x.strategy === 'least-distance')) {
    const short = router.route(r.from, r.to, 'least-distance');
    const few = router.route(r.from, r.to, 'minimum-interchange');
    assert.ok(few.changes <= short.changes);
    for (const route of [short, few]) {
      assert.equal(route.legs[0].origin, r.from);
      assert.equal(route.legs[route.legs.length - 1].destination, r.to);
      for (let i = 1; i < route.legs.length; i += 1) {
        const prev = route.legs[i - 1];
        const leg = route.legs[i];
        // A change happens at one station; a walk links two different ones.
        assert.ok(prev.destination === leg.origin || leg.kind === 'transfer' || prev.kind === 'transfer');
      }
    }
  }
});

test('a trip within one operator stays on that operator', () => {
  const dmrc = reference.find((r) => r.from.startsWith('dmrc:') && r.to.startsWith('dmrc:'));
  const route = router.route(dmrc.from, dmrc.to, 'least-distance');
  for (const leg of route.legs) for (const stop of leg.stops) assert.ok(stop.startsWith('dmrc:'));
});

test('Airport Express can be left out', () => {
  const airport = graph.patterns.find((p) => p.id === 'dmrc:LN10');
  if (!airport) return;
  const from = airport.stops[0];
  const to = airport.stops[airport.stops.length - 1];
  const route = router.route(from, to, 'least-distance', { excludeAirport: true });
  if (route) for (const leg of route.legs) assert.notEqual(leg.pattern, 'dmrc:LN10');
});

test('an override wins for its pair, and one that no longer fits the graph is ignored', () => {
  const pattern = graph.patterns.find((p) => p.network === 'dmrc' && !p.loop && p.stops.length > 4);
  const [a, b, c] = pattern.stops;
  const override = { from: a, to: c, strategy: 'least-distance', legs: [{ kind: 'metro', pattern: pattern.id, origin: a, destination: c, stops: [a, b, c] }] };
  const withOverride = new OfflineRouter(graph, [override]);
  assert.equal(withOverride.route(a, c, 'least-distance').fromOverride, true);
  const broken = { ...override, legs: [{ ...override.legs[0], stops: [a, 'dmrc:NOPE', c] }] };
  assert.equal(new OfflineRouter(graph, [broken]).route(a, c, 'least-distance').fromOverride, false);
});

test('offline fares price each operator on its own ticket', () => {
  const fares = {
    dmrc_distance_slabs: [{ max_km: 2, normal: 11, special: 11 }, { max_km: 12, normal: 32, special: 21 }, { max_km: null, normal: 64, special: 54 }],
    nmrc_station_count_slabs: [{ max_stations: 2, normal: 10, special: 10 }, { max_stations: 30, normal: 50, special: 50 }],
    ncrtc_fare_matrix: [
      { from: 'ncrtc:Z00', to: 'ncrtc:A04', class: 'standard', amount: 80 },
      { from: 'ncrtc:Z00', to: 'ncrtc:A04', class: 'premium', amount: 95 },
    ],
  };
  const route = {
    legs: [
      { kind: 'metro', pattern: 'dmrc:LN3', origin: 'dmrc:A', destination: 'dmrc:B', stops: ['dmrc:A', 'dmrc:B'], km: 5, minutes: 10 },
      { kind: 'transfer', pattern: null, origin: 'dmrc:B', destination: 'ncrtc:Z00', stops: [], km: 0, minutes: 10 },
      { kind: 'metro', pattern: 'ncrtc:RRTS', origin: 'ncrtc:Z00', destination: 'ncrtc:A04', stops: ['ncrtc:Z00', 'ncrtc:A01', 'ncrtc:A04'], km: 20, minutes: 20 },
    ],
  };
  const fare = offlineFare(route, fares);
  assert.equal(fare.normal, 32 + 80);
  assert.equal(fare.breakdown.length, 2);
  assert.deepEqual(JSON.parse(JSON.stringify(fare.classes)), [{ class: 'standard', amount: 80 }, { class: 'premium', amount: 95 }]);
  // Meerut Metro sells no Premium.
  route.legs[2].pattern = 'ncrtc:MRTS';
  assert.deepEqual(JSON.parse(JSON.stringify(offlineFare(route, fares).classes)), []);
});
